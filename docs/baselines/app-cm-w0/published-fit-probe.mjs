import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync } from 'node:fs';
import { createClusterMeshModules, verifyClusterMeshTopology } from '@sentropic/cluster-mesh';
import { createArtifactsManifest } from '@sentropic/artifacts/mcp';
import { RADAR_ARTIFACTS_PROFILE } from '@sentropic/artifacts';
import { compileArtifactsProfile } from '@sentropic/artifacts';
const modules = createClusterMeshModules();
const comments = await modules.load('comments');
assert.equal(typeof comments.createCommentsModule, 'function');
assert.equal(typeof comments.createCommentsPostgresStorage, 'function');
const gateway = await modules.load('gateway');
assert.equal(typeof gateway.createGatewayRouter, 'function');
const topology = verifyClusterMeshTopology({ require: ['llm-mesh', 'gateway'] });
assert.equal(topology.instances.length, 1);
assert.equal(topology.llmMesh.path, topology.gateway.llmMesh.path);
const selected = ['artifacts_ensure','artifacts_publish','artifacts_list','artifacts_get'];
const profile = compileArtifactsProfile(RADAR_ARTIFACTS_PROFILE);
const manifest = createArtifactsManifest({ profile });
assert.deepEqual(manifest.tools.map(tool=>tool.name).sort(), [...selected].sort());
assert.throws(()=>createArtifactsManifest({selectedCapabilities:selected}));
const lock=JSON.parse(readFileSync('package-lock.json','utf8'));
assert.equal(Object.values(lock.packages).some(pkg=>pkg.link),false);
const resolved=Object.fromEntries(Object.entries(lock.packages).map(([path,pkg])=>[path,{version:pkg.version,resolved:pkg.resolved,integrity:pkg.integrity}]));
console.log(JSON.stringify({commentsLoaded:true,gatewayLoaded:true,sharedLlmMesh:true,clusterCopies:topology.instances.length,selected:manifest.tools.map(t=>t.name),profileDigest:profile.profileDigest,sourceLinks:0,lockSha256:createHash('sha256').update(readFileSync('package-lock.json')).digest('hex'),resolvedTree:resolved,physicalCluster:realpathSync('node_modules/@sentropic/cluster-mesh')}));
