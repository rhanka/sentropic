// A2.3 identity slice: the PostgreSQL profile of this lot's store slice —
// the conversation authority store and the audit/escalation ledger over the
// kernel's published `InjectedPgDriver` protocol. The schema is host-owned
// and parameterized (never hardcoded); the package ships its own DDL through
// `identityEnforcementPgSchema()`. Entries are sealed exactly like the
// in-memory double: the draft is stored canonically and the hash chain is
// recomputed by the same shared verifier, so tamper detection behaves
// identically on every profile.

import { quotePgIdentifier } from '../storage/postgres/protocol.js';
import type { InjectedPgDriver, PgSession } from '../storage/postgres/protocol.js';
import { ConversationSessionError, type ConversationAuthorityStore, type ConversationSessionRecord } from './conversation.js';
import {
  escalationEntryDigest,
  verifyEscalationChainsOf,
  type EscalationChainVerification,
  type EscalationLedgerEntry,
  type EscalationLedgerEntryDraft,
  type EscalationLedgerQuery,
  type IdentityLedgerStore,
} from './ledger.js';
import type { IdentityAuditEvent } from '../identity-contracts/types.js';

const TX_WRITE = { isolation: 'serializable', readOnly: false, deadlineMs: 5000 } as const;
const TX_READ = { isolation: 'serializable', readOnly: true, deadlineMs: 5000 } as const;

/** Package-owned DDL for the A2.3 slice; `schema` is host-created. */
export function identityEnforcementPgSchema(schema: string): readonly string[] {
  const s = quotePgIdentifier(schema);
  return [
    `CREATE TABLE IF NOT EXISTS ${s}.cm_identity_conversation_sessions (
      conversation_session_id text PRIMARY KEY,
      user_id text NOT NULL,
      workspace_id text NOT NULL,
      status text NOT NULL,
      opened_at text NOT NULL,
      expires_at text NOT NULL,
      revoked_at text)`,
    `CREATE INDEX IF NOT EXISTS cm_identity_conversation_sessions_user
      ON ${s}.cm_identity_conversation_sessions (user_id)`,
    `CREATE TABLE IF NOT EXISTS ${s}.cm_identity_audit_events (
      ordinal bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      at text NOT NULL,
      kind text NOT NULL,
      actor_id text,
      subject_id text,
      detail text)`,
    `CREATE TABLE IF NOT EXISTS ${s}.cm_identity_escalation_entries (
      ordinal bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      escalation_id text NOT NULL,
      owner_user_id text NOT NULL,
      workspace_id text NOT NULL,
      target_ref text NOT NULL,
      entry_json jsonb NOT NULL,
      prev_entry_hash text,
      entry_hash text NOT NULL)`,
    `CREATE INDEX IF NOT EXISTS cm_identity_escalation_entries_escalation
      ON ${s}.cm_identity_escalation_entries (escalation_id)`,
  ];
}

const rowToConversationSession = (row: Record<string, unknown>): ConversationSessionRecord => ({
  conversationSessionId: row.conversation_session_id as string,
  userId: row.user_id as string,
  workspaceId: row.workspace_id as string,
  status: row.status as ConversationSessionRecord['status'],
  openedAt: row.opened_at as string,
  expiresAt: row.expires_at as string,
  revokedAt: (row.revoked_at as string | null) ?? undefined,
});

const rowToEscalationEntry = (row: Record<string, unknown>): EscalationLedgerEntry => ({
  ...(typeof row.entry_json === 'string'
    ? (JSON.parse(row.entry_json) as EscalationLedgerEntryDraft)
    : (row.entry_json as EscalationLedgerEntryDraft)),
  prevEntryHash: (row.prev_entry_hash as string | null) ?? null,
  entryHash: row.entry_hash as string,
});

const rowToAuditEvent = (row: Record<string, unknown>): IdentityAuditEvent => ({
  at: row.at as string,
  kind: row.kind as string,
  actorId: (row.actor_id as string | null) ?? undefined,
  subjectId: (row.subject_id as string | null) ?? undefined,
  detail: (row.detail as string | null) ?? undefined,
});

export function createPostgresIdentityStores(input: {
  readonly driver: InjectedPgDriver;
  readonly schema: string;
}): {
  readonly conversations: ConversationAuthorityStore;
  readonly ledger: IdentityLedgerStore;
} {
  const s = quotePgIdentifier(input.schema);
  const write = <T>(operation: (session: PgSession) => Promise<T>): Promise<T> =>
    input.driver.transaction(TX_WRITE, operation);
  const read = <T>(operation: (session: PgSession) => Promise<T>): Promise<T> =>
    input.driver.transaction(TX_READ, operation);

  const conversations: ConversationAuthorityStore = {
    async saveSession(record) {
      await write((session) =>
        session.execute({
          text: `INSERT INTO ${s}.cm_identity_conversation_sessions
            (conversation_session_id, user_id, workspace_id, status, opened_at, expires_at, revoked_at)
            VALUES ($1, $2, $3, $4, $5, $6, $7)
            ON CONFLICT (conversation_session_id) DO UPDATE SET
              user_id = EXCLUDED.user_id,
              workspace_id = EXCLUDED.workspace_id,
              status = EXCLUDED.status,
              opened_at = EXCLUDED.opened_at,
              expires_at = EXCLUDED.expires_at,
              revoked_at = EXCLUDED.revoked_at`,
          values: [
            record.conversationSessionId,
            record.userId,
            record.workspaceId,
            record.status,
            record.openedAt,
            record.expiresAt,
            record.revokedAt ?? null,
          ],
        }),
      );
    },
    async findSession(conversationSessionId) {
      const result = await read((session) =>
        session.execute({
          text: `SELECT * FROM ${s}.cm_identity_conversation_sessions WHERE conversation_session_id = $1`,
          values: [conversationSessionId],
        }),
      );
      return result.rows[0] ? rowToConversationSession(result.rows[0]) : null;
    },
    async revokeSession(conversationSessionId, at) {
      const result = await write((session) =>
        session.execute({
          text: `UPDATE ${s}.cm_identity_conversation_sessions
            SET status = 'revoked', revoked_at = $2
            WHERE conversation_session_id = $1
            RETURNING *`,
          values: [conversationSessionId, at],
        }),
      );
      if (result.rows.length === 0) throw new ConversationSessionError('not_found');
      return rowToConversationSession(result.rows[0]);
    },
    async listSessionsForUser(userId) {
      const result = await read((session) =>
        session.execute({
          text: `SELECT * FROM ${s}.cm_identity_conversation_sessions WHERE user_id = $1 ORDER BY opened_at, conversation_session_id`,
          values: [userId],
        }),
      );
      return result.rows.map(rowToConversationSession);
    },
  };

  const ledger: IdentityLedgerStore = {
    async append(event) {
      await write((session) =>
        session.execute({
          text: `INSERT INTO ${s}.cm_identity_audit_events (at, kind, actor_id, subject_id, detail)
            VALUES ($1, $2, $3, $4, $5)`,
          values: [event.at, event.kind, event.actorId ?? null, event.subjectId ?? null, event.detail ?? null],
        }),
      );
    },
    async listAuditEvents() {
      const result = await read((session) =>
        session.execute({ text: `SELECT * FROM ${s}.cm_identity_audit_events ORDER BY ordinal`, values: [] }),
      );
      return result.rows.map(rowToAuditEvent);
    },
    async appendEscalationEntry(draft) {
      return write(async (session) => {
        const tail = await session.execute({
          text: `SELECT entry_hash FROM ${s}.cm_identity_escalation_entries
            WHERE escalation_id = $1 ORDER BY ordinal DESC LIMIT 1`,
          values: [draft.escalationId],
        });
        const prevEntryHash = (tail.rows[0]?.entry_hash as string | undefined) ?? null;
        const entry: EscalationLedgerEntry = {
          ...draft,
          prevEntryHash,
          entryHash: escalationEntryDigest(draft, prevEntryHash),
        };
        await session.execute({
          text: `INSERT INTO ${s}.cm_identity_escalation_entries
            (escalation_id, owner_user_id, workspace_id, target_ref, entry_json, prev_entry_hash, entry_hash)
            VALUES ($1, $2, $3, $4, $5::jsonb, $6, $7)`,
          values: [
            draft.escalationId,
            draft.ownerUserId,
            draft.workspaceId,
            draft.targetRef,
            JSON.stringify(draft),
            prevEntryHash,
            entry.entryHash,
          ],
        });
        return entry;
      });
    },
    async listEscalationChain(escalationId) {
      const result = await read((session) =>
        session.execute({
          text: `SELECT * FROM ${s}.cm_identity_escalation_entries WHERE escalation_id = $1 ORDER BY ordinal`,
          values: [escalationId],
        }),
      );
      return result.rows.map(rowToEscalationEntry);
    },
    async listEscalations(query: EscalationLedgerQuery) {
      const clauses: string[] = [];
      const values: (string | null)[] = [];
      if (query.ownerUserId !== undefined) {
        values.push(query.ownerUserId);
        clauses.push(`owner_user_id = $${values.length}`);
      }
      if (query.workspaceId !== undefined) {
        values.push(query.workspaceId);
        clauses.push(`workspace_id = $${values.length}`);
      }
      if (query.targetRef !== undefined) {
        values.push(query.targetRef);
        clauses.push(`target_ref = $${values.length}`);
      }
      const where = clauses.length > 0 ? ` WHERE ${clauses.join(' AND ')}` : '';
      const result = await read((session) =>
        session.execute({
          text: `SELECT * FROM ${s}.cm_identity_escalation_entries${where} ORDER BY ordinal`,
          values,
        }),
      );
      return result.rows.map(rowToEscalationEntry);
    },
    async verifyEscalationChains(): Promise<readonly EscalationChainVerification[]> {
      const result = await read((session) =>
        session.execute({
          text: `SELECT * FROM ${s}.cm_identity_escalation_entries ORDER BY escalation_id, ordinal`,
          values: [],
        }),
      );
      return verifyEscalationChainsOf(result.rows.map(rowToEscalationEntry));
    },
  };

  return { conversations, ledger };
}
